"""Explicit host-test catalog; paths are repository-relative unless absolute."""
from dataclasses import dataclass


@dataclass(frozen=True)
class NativeCase:
    name: str
    sources: tuple[str, ...]
    standard: str = "c++17"
    include_dirs: tuple[str, ...] = ("include",)
    flags: tuple[str, ...] = ("-Wall", "-Wextra", "-Werror", "-static")
    libraries: tuple[str, ...] = ()
    library_dirs: tuple[str, ...] = ()
    system_include_dirs: tuple[str, ...] = ()
    c_sources: tuple[str, ...] = ()
    graphics: bool = False
    runtime_inputs: tuple[str, ...] = ()
    coverage_sources: tuple[str, ...] = ()


def _group(names, sources=(), **options):
    return tuple(NativeCase(name, ("tests/" + name + ".cpp", *sources), **options) for name in names)


