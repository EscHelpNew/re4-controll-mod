"""Generate serif coverage geometry from the unmodified OFL font; no game assets."""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont
font=ImageFont.truetype('assets/fonts/liberation-serif/LiberationSerif-BoldItalic.ttf',24)
cap=-font.getbbox('H',anchor='ls')[1]
assert cap==16
chars=list(range(32,127))+[0x401]+list(range(0x410,0x450))+[0x451]
runs=[];glyphs=[]
for code in sorted(chars):
 c=chr(code);box=font.getbbox(c,anchor='ls');l,t,r,b=box;im=Image.new('L',(max(1,r-l),max(1,b-t)));ImageDraw.Draw(im).text((-l,-t),c,font=font,fill=255,anchor='ls')
 start=len(runs)
 for y in range(im.height):
  x=0
  while x<im.width:
   a=min(255,((im.getpixel((x,y))+16)//32)*32)
   if not a:x+=1;continue
   first=x;x+=1
   while x<im.width and min(255,((im.getpixel((x,y))+16)//32)*32)==a:x+=1
   runs.append((first+l,y+t+cap,x-first,a))
 glyphs.append((code,start,len(runs)-start,round(font.getlength(c)*64)))
out=Path('include/re4/serif_glyphs.inc')
s='// Generated by tools/generate_serif_glyphs.py from Liberation Serif Bold Italic 2.1.5.\n// Coverage geometry is licensed under SIL OFL 1.1; see assets/fonts/liberation-serif/LICENSE.\n'
s+='inline constexpr SerifRun serif_runs[]={\n'+''.join('{%d,%d,%d,%d},\n'%v for v in runs)+'};\n'
s+='inline constexpr SerifGlyph serif_glyphs[]={\n'+''.join('{%d,%d,%d,%d},\n'%v for v in glyphs)+'};\n'
out.write_text(s)
print('capheight',cap,'glyphs',len(glyphs),'runs',len(runs),'bytes',out.stat().st_size)
