template<std::size_t N> inline bool check(const std::uint8_t* memory,std::size_t size,std::size_t minimum,
 std::size_t offset,const BuildId& expected,const Site (&sites)[N]){
 if(!memory||size<minimum||offset>size||size-offset<expected.size()||std::memcmp(memory+offset,expected.data(),expected.size()))return false;
 for(auto site:sites){std::uint32_t word=0;if(site.offset>size||size-site.offset<4)return false;std::memcpy(&word,memory+site.offset,4);if(word!=site.instruction)return false;}
 return true;
}
struct View {Build build=Build::None;std::size_t id_offset=0;const BuildId* id=nullptr;const Site* sites=nullptr;std::size_t count=0;};
constexpr View view(Build build){
 if(build==Build::Latest)return {build,build_id_offset,&build_id,main_sites,std::size(main_sites)};
 if(build==Build::Legacy)return {build,legacy_build_id_offset,&legacy_build_id,legacy_main_sites,std::size(legacy_main_sites)};
 return {};
}
inline Build detect(const std::uint8_t* memory,std::size_t size){
 const bool latest=check(memory,size,main_size,build_id_offset,build_id,main_sites);
 const bool legacy=check(memory,size,main_size,legacy_build_id_offset,legacy_build_id,legacy_main_sites);
 return latest==legacy?Build::None:latest?Build::Latest:Build::Legacy;
}
inline bool matches(const std::uint8_t* memory,std::size_t size){return detect(memory,size)!=Build::None;}
